std::string import_script(
    const std::filesystem::path& obj_path,
    const std::optional<std::filesystem::path>& save_blend_path) {

    std::ostringstream out;
    out <<
R"(# Generated by Auto CAD Pro.
import bpy

OBJ_PATH = )" << python_string(obj_path) << R"(
SAVE_BLEND_PATH = )";
    if (save_blend_path.has_value()) {
        out << python_string(*save_blend_path);
    } else {
        out << "None";
    }

    out << "\nACP_TO_METERS = "
        << python_number(units::canonical_to_meters(1.0))
        << R"(

# Auto CAD Pro canonical geometry is millimeters. Blender's scene is metric,
# so imported geometry is converted explicitly to meters. This prevents an
# architectural 3000 mm wall from becoming a 3000 m wall.
scene = bpy.context.scene
scene.unit_settings.system = 'METRIC'
scene.unit_settings.scale_length = 1.0

# Import across current Blender versions, with a fallback for older versions.
if hasattr(bpy.ops.wm, "obj_import"):
    bpy.ops.wm.obj_import(filepath=OBJ_PATH)
else:
    bpy.ops.import_scene.obj(filepath=OBJ_PATH)

imported = list(bpy.context.selected_objects)

CATEGORY_PREFIXES = {
    "Wall_": "ACP_Walls",
    "Slab_": "ACP_Slabs",
    "Column_": "ACP_Columns",
    "Beam_": "ACP_Beams",
    "Door_": "ACP_Doors",
    "Window_": "ACP_Windows",
    "Roof_": "ACP_Roofs",
    "Stair_": "ACP_Stairs",
}

def ensure_collection(name):
    collection = bpy.data.collections.get(name)
    if collection is None:
        collection = bpy.data.collections.new(name)
        scene.collection.children.link(collection)
    return collection

def classify(name):
    for prefix, collection_name in CATEGORY_PREFIXES.items():
        if name.startswith(prefix):
            return prefix[:-1], collection_name
    return "Generic", "ACP_Generic"

for obj in imported:
    # OBJ has no standard unit metadata. Convert ACP's canonical millimeters to
    # Blender meters at the bridge boundary and apply the transform so later
    # modifiers/material workflows see real metric dimensions.
    obj.scale = tuple(component * ACP_TO_METERS for component in obj.scale)
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)

    kind, collection_name = classify(obj.name)
    obj["auto_cad_pro_source"] = True
    obj["auto_cad_pro_kind"] = kind
    obj["auto_cad_pro_source_unit"] = "millimeter"
    target = ensure_collection(collection_name)
    for collection in list(obj.users_collection):
        collection.objects.unlink(obj)
    target.objects.link(obj)

if SAVE_BLEND_PATH:
    bpy.ops.wm.save_as_mainfile(filepath=SAVE_BLEND_PATH)
)";

    return out.str();
}

std::optional<Bundle> write_bundle(
    const std::filesystem::path& directory,
    const model3d::Scene& scene,
    const std::optional<std::filesystem::path>& save_blend_path) {

    std::error_code error;
    std::filesystem::create_directories(directory, error);
    if (error) {
        return std::nullopt;
    }

    const std::filesystem::path obj_path =
        directory / "auto_cad_pro_scene.obj";
    const std::filesystem::path script_path =
        directory / "import_auto_cad_pro.py";

    if (!obj::save(obj_path, scene)) {
        return std::nullopt;
    }

    std::ofstream script(script_path, std::ios::binary | std::ios::trunc);
    if (!script) {
        return std::nullopt;
    }
    const std::string content = import_script(obj_path, save_blend_path);
    script.write(content.data(), static_cast<std::streamsize>(content.size()));
    script.flush();
    if (!script.good()) {
        return std::nullopt;
    }

    return Bundle{obj_path, script_path};
}

std::string command_line(
    const std::filesystem::path& blender_executable,
    const std::filesystem::path& script_path) {

    return quote_command_arg(blender_executable) +
           " --python " +
           quote_command_arg(script_path);
}

