std::string python_string(const std::filesystem::path& path) {
    const std::string raw = path.generic_string();
    std::string escaped;
    escaped.reserve(raw.size() + 8);
    for (const char ch : raw) {
        switch (ch) {
            case '\\': escaped += "\\\\"; break;
            case '\'': escaped += "\\'"; break;
            case '\n': escaped += "\\n"; break;
            case '\r': escaped += "\\r"; break;
            default: escaped += ch; break;
        }
    }
    return "'" + escaped + "'";
}

std::string quote_command_arg(const std::filesystem::path& path) {
    const std::string raw = path.string();
    std::string quoted = "\"";
    for (const char ch : raw) {
        if (ch == '\"') {
            quoted += "\\\"";
        } else {
            quoted += ch;
        }
    }
    quoted += "\"";
    return quoted;
}

std::string python_number(double value) {
    std::ostringstream out;
    out << std::setprecision(17) << value;
    return out.str();
}

